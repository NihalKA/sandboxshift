def _validate_workspace(workspace_str: str) -> Path:
    """Validate workspace path: must exist and must not be a sensitive root."""
    p = Path(workspace_str).expanduser()
    if not p.exists():
        print(f"Error: workspace does not exist: {workspace_str!r}", file=sys.stderr)
        sys.exit(1)
    resolved = p.resolve()
    for sensitive in _SENSITIVE_ROOTS:
        try:
            sensitive_resolved = sensitive.resolve()
            if resolved == sensitive_resolved or sensitive_resolved in resolved.parents:
                print(
                    f"Error: workspace {resolved!r} is inside a protected directory"
                    f" ({sensitive_resolved}). Refusing to run.",
                    file=sys.stderr,
                )
                sys.exit(1)
        except Exception:  # noqa: BLE001
            pass
    return resolved


def _validate_allow_hosts(hosts: list[str]) -> None:
    """Reject bare IP addresses and non-FQDN values in --allow.

    "*" is accepted as a special sentinel for unrestricted network mode
    (Decision #54). All other entries must be FQDNs — bare IPs including
    IMDS 169.254.169.254 are rejected.
    """
    for host in hosts:
        # "*" is the unrestricted-network sentinel — bypass all checks.
        if host == "*":
            continue
        # Reject bare IP addresses outright (IPv4 and IPv6).
        try:
            ipaddress.ip_address(host)
            print(
                f"Error: --allow does not accept IP addresses: {host!r}. Use FQDNs only.",
                file=sys.stderr,
            )
            sys.exit(1)
        except ValueError:
            pass
        # Require a valid FQDN (at least two dot-separated labels).
        if not _FQDN_RE.match(host):
            print(
                f"Error: --allow requires a valid fully-qualified domain name: {host!r}",
                file=sys.stderr,
            )
            sys.exit(1)


def _parse_port(port_str: str) -> tuple[int, int]:
    """Parse port string. Accepts bare PORT or HOST:CONTAINER format.

    Bare port (e.g. '3000') expands to (3000, 3000) — same host and container port.
    HOST:CONTAINER (e.g. '8080:3000') maps host 8080 to container 3000.

    Raises ValueError on invalid input.
    """
    parts = port_str.split(":")
    if len(parts) == 1:
        # Bare port number — expand to HOST:CONTAINER both equal.
        try:
            port = int(parts[0])
        except ValueError:
            raise ValueError(
                f"Invalid port '{port_str}': must be an integer (e.g. 3000) "
                f"or HOST:CONTAINER (e.g. 8080:3000)"
            )
        if not (1 <= port <= 65535):
            raise ValueError(f"Port {port} out of valid range (1-65535)")
        return (port, port)
    if len(parts) != 2:
        raise ValueError(
            f"Invalid port format '{port_str}': expected PORT or HOST:CONTAINER "
            f"(e.g. 3000 or 8080:3000)"
        )
    try:
        host, container = int(parts[0]), int(parts[1])
    except ValueError:
        raise ValueError(f"Port numbers in '{port_str}' must be integers")
    if not (1 <= host <= 65535):
        raise ValueError(f"Host port {host} out of valid range (1-65535)")
    if not (1 <= container <= 65535):
        raise ValueError(f"Container port {container} out of valid range (1-65535)")
    return (host, container)


def _build_fargate_runtime(audit_logger: AuditLogger) -> FargateRuntime | None:
    """Build FargateRuntime from environment variables, or return None if any required vars are missing.

    Required vars (see _FARGATE_ENV_VARS):
      FARGATE_CLUSTER_ARN, FARGATE_EXECUTION_ROLE_ARN, FARGATE_TASK_ROLE_ARN,
      FARGATE_SUBNET_IDS, FARGATE_SECURITY_GROUP_IDS, FARGATE_LOG_GROUP,
      FARGATE_REGION, FARGATE_WORKSPACE_BUCKET

    Optional vars:
      FARGATE_SERVER_SECURITY_GROUP_ID — if absent, server mode tasks will launch
        without ALL-TCP inbound (ports won't be publicly reachable).
      FARGATE_TASK_FAMILY — prefix for dynamic task def family names
        (default: 'sandboxshift-sandbox').
      FARGATE_ECR_IMAGE — full container image URI; if absent or empty,
        defaults to 'sandboxshift/runtime-multi:latest' (Docker Hub).
    """
    values = {k: os.environ.get(k, "").strip() for k in _FARGATE_ENV_VARS}
    if any(v == "" for v in values.values()):
        return None
    server_sg_id = os.environ.get("FARGATE_SERVER_SECURITY_GROUP_ID", "").strip() or None
    task_family = os.environ.get("FARGATE_TASK_FAMILY", "sandboxshift-sandbox").strip()
    ecr_image = os.environ.get("FARGATE_ECR_IMAGE", "").strip()
    return FargateRuntime(
        cluster_arn=values["FARGATE_CLUSTER_ARN"],
        execution_role_arn=values["FARGATE_EXECUTION_ROLE_ARN"],
        task_role_arn=values["FARGATE_TASK_ROLE_ARN"],
        subnet_ids=values["FARGATE_SUBNET_IDS"].split(","),
        security_group_ids=values["FARGATE_SECURITY_GROUP_IDS"].split(","),
        region=values["FARGATE_REGION"],
        log_group=values["FARGATE_LOG_GROUP"],
        workspace_bucket=values["FARGATE_WORKSPACE_BUCKET"],
        task_family=task_family,
        ecr_image=ecr_image,
        server_security_group_id=server_sg_id,
        audit_logger=audit_logger,
    )


def _resolve_audit_log(args: argparse.Namespace) -> Path:
    """Resolve audit log path: --audit-log arg → env var → default."""
    if args.audit_log:
        return Path(args.audit_log).expanduser()
    env_val = os.environ.get("SANDBOXSHIFT_AUDIT_LOG", "").strip()
    if env_val:
        return Path(env_val).expanduser()
    return _DEFAULT_AUDIT_LOG


