_MEMORY_MB_MAX = 65536
_CPU_MIN = 0.25
_CPU_MAX = 64.0

# Hardcoded last-resort defaults used when neither CLI flag nor YAML provides a value.
_DEFAULT_CPU = 1.0
_DEFAULT_MEMORY_MB = 512
_DEFAULT_TIMEOUT = 1800


