def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="sandboxshift",
        description="Run AI agent tasks in isolated sandboxes (local or cloud)",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    # ── sandboxshift run ──────────────────────────────────────────────────────
    run_parser = subparsers.add_parser("run", help="Run a task in a sandbox")
    run_parser.add_argument("workspace", help="Path to workspace directory")
    run_parser.add_argument("task", help="Shell command to run")
    run_parser.add_argument(
        "--mode",
        choices=["local", "cloud", "auto"],
        default="auto",
        help=(
            "Run mode: 'local' (always run in Podman), 'cloud' (always burst to Fargate), "
            "'auto' (default — decide based on available RAM and --ram-threshold). "
            "Overrides YAML sandbox.mode. Never overrides sensitive-data detection."
        ),
    )
    run_parser.add_argument(
        "--memory-mb",
        dest="memory_mb",
        type=int,
        default=None,
        help=(
            "Memory limit in MB (default: from sandboxshift.yaml resources.memory, "
            f"or {_DEFAULT_MEMORY_MB} MB if not set). "
            "For cloud: baked into the ECS task definition registered per run."
        ),
    )
    run_parser.add_argument(
        "--cpu",
        type=float,
        default=None,
        help=(
            "CPU limit in vCPUs (default: from sandboxshift.yaml resources.cpu, "
            f"or {_DEFAULT_CPU} vCPU if not set). "
            "For cloud: baked into the ECS task definition registered per run."
        ),
    )
    run_parser.add_argument(
        "--timeout",
        type=int,
        default=None,
        help=(
            "Task timeout in seconds (default: from sandboxshift.yaml sandbox.timeout, "
            f"or {_DEFAULT_TIMEOUT}s if not set)."
        ),
    )
    run_parser.add_argument(
        "--allow",
        action="append",
        default=[],
        metavar="FQDN",
        help="Allow outbound access to FQDN (repeat for multiple). Use '*' for unrestricted.",
    )
    run_parser.add_argument(
        "--setup",
        default=None,
        help="Setup command to run before the task",
    )
    run_parser.add_argument(
        "--port",
        dest="ports",
        action="append",
        default=[],
        metavar="PORT|HOST:CONTAINER",
        help="Expose container port (e.g. 3000 or 8080:3000). Repeat for multiple.",
    )
    run_parser.add_argument(
        "--ram-threshold",
        dest="ram_threshold",
        type=int,
        default=1024,
        help=(
            "Available RAM threshold in MB. If available RAM < N, burst to cloud "
            "(default: 1024). Only used when --mode is 'auto'."
        ),
    )
    run_parser.add_argument(
        "--skip-sensitivity-check",
        dest="skip_sensitivity_check",
        action="store_true",
        default=False,
        help="Skip sensitive data detection (use with caution)",
    )
    run_parser.add_argument(
        "--audit-log",
        dest="audit_log",
        default=None,
        help="Path to audit log file (default: ~/.sandboxshift/audit.log)",
    )
    run_parser.set_defaults(func=_cmd_run)

    # ── sandboxshift list ─────────────────────────────────────────────────
    list_parser = subparsers.add_parser(
        "list",
        help="List running cloud server tasks",
    )
    list_parser.set_defaults(func=_cmd_list)

    # ── sandboxshift stop ─────────────────────────────────────────────────
    stop_parser = subparsers.add_parser(
        "stop",
        help="Stop a running cloud server task",
    )
    stop_parser.add_argument(
        "instance_id",
        help="Instance ID printed by 'sandboxshift run' (e.g. ss-abc123def456)",
    )
    stop_parser.set_defaults(func=_cmd_stop)

    # ── sandboxshift audit ─────────────────────────────────────────────────
    audit_parser = subparsers.add_parser("audit", help="Audit trail commands")
    audit_subparsers = audit_parser.add_subparsers(dest="audit_command", required=True)

    tail_parser = audit_subparsers.add_parser("tail", help="Show recent audit log entries")
    tail_parser.add_argument(
        "-n",
        dest="lines",
        type=int,
        default=20,
        help="Number of recent entries to show (default: 20)",
    )
    tail_parser.add_argument(
        "--audit-log",
        dest="audit_log",
        default=None,
        help="Path to audit log file (default: ~/.sandboxshift/audit.log)",
    )
    tail_parser.set_defaults(func=_cmd_audit_tail)

    return parser


def main() -> None:
    """Entry point for the sandboxshift CLI."""
    parser = _build_parser()
    args = parser.parse_args()
    args.func(args)
