async def _run_async(args: argparse.Namespace, workspace: Path) -> RunResult:
    # Load YAML config from workspace (returns {} if sandboxshift.yaml absent).
    yaml_cfg = load_workspace_config(Path(args.workspace))

    # Parse CLI --port flags; exit(1) on invalid input.
    parsed_ports: list[tuple[int, int]] = []
    for port_str in (args.ports or []):
        try:
            parsed_ports.append(_parse_port(port_str))
        except ValueError as e:
            print(f"Error: {e}", file=sys.stderr)
            sys.exit(1)

    # Combine YAML ports with CLI ports (YAML first, then CLI), deduped.
    yaml_ports = yaml_cfg.get("ports", [])
    all_ports: list[tuple[int, int]] = []
    seen: set[tuple[int, int]] = set()
    for p in [*yaml_ports, *parsed_ports]:
        pt = (int(p[0]), int(p[1]))
        if pt not in seen:
            seen.add(pt)
            all_ports.append(pt)

    # For each resource field the merge priority is:
    #   CLI flag (explicit) → sandboxshift.yaml → hardcoded default
    # --cpu / --memory-mb / --timeout default to None in argparse so we can
    # distinguish "user did not pass this flag" from "user passed the value".

    # setup_command: CLI --setup wins over YAML.
    effective_setup = args.setup if args.setup is not None else yaml_cfg.get("setup_command")
    # network_allow: CLI --allow wins over YAML.
    effective_allow = list(args.allow) if args.allow else yaml_cfg.get("network_allow", [])
    # skip_sensitivity_check: CLI --skip-sensitivity-check wins over YAML.
    skip_scan = args.skip_sensitivity_check or yaml_cfg.get("skip_sensitivity_check", False)
    # workspace_readonly: YAML only (no CLI flag in V1).
    workspace_readonly = yaml_cfg.get("workspace_readonly", False)
    # min resource requirements: YAML only (no CLI flags in V1).
    min_cpu_required = yaml_cfg.get("min_cpu_required", 0.0)
    min_memory_mb_required = yaml_cfg.get("min_memory_mb_required", 0)
    # cpu_limit: CLI --cpu wins over YAML resources.cpu.
    effective_cpu = (
        args.cpu if args.cpu is not None
        else yaml_cfg.get("cpu_limit", _DEFAULT_CPU)
    )
    # memory_limit_mb: CLI --memory-mb wins over YAML resources.memory.
    effective_memory_mb = (
        args.memory_mb if args.memory_mb is not None
        else yaml_cfg.get("memory_limit_mb", _DEFAULT_MEMORY_MB)
    )
    # timeout_seconds: CLI --timeout wins over YAML sandbox.timeout.
    effective_timeout = (
        args.timeout if args.timeout is not None
        else yaml_cfg.get("timeout_seconds", _DEFAULT_TIMEOUT)
    )

    config = SandboxConfig(
        cpu_limit=effective_cpu,
        memory_limit_mb=effective_memory_mb,
        network_allow=effective_allow,
        timeout_seconds=effective_timeout,
        setup_command=effective_setup,
        ports=all_ports,
        skip_sensitivity_check=skip_scan,
        workspace_readonly=workspace_readonly,
        min_cpu_required=min_cpu_required,
        min_memory_mb_required=min_memory_mb_required,
    )

    audit_log_path = _resolve_audit_log(args)
    audit_logger = AuditLogger(log_path=audit_log_path)

    fargate_runtime = _build_fargate_runtime(audit_logger)
    podman_runtime = PodmanRuntime(audit_logger=audit_logger)

    # Resolve effective run mode.
    # Priority: CLI --mode (if not "auto") > YAML sandbox.mode > --ram-threshold.
    # --mode local  → threshold=0.0      (available RAM always ≥ 0 → always local)
    # --mode cloud  → threshold=+inf     (available RAM never ≥ inf → always cloud)
    # --mode auto   → check YAML sandbox.mode, then fall back to --ram-threshold
    effective_mode = args.mode if args.mode != "auto" else yaml_cfg.get("sandbox_mode", "auto")
    if effective_mode == "local":
        effective_threshold_gb = 0.0
    elif effective_mode == "cloud":
        effective_threshold_gb = float("inf")
    else:  # auto
        effective_threshold_gb = args.ram_threshold / 1024

    burst_engine = BurstEngine(ram_threshold_gb=effective_threshold_gb)

    manager = SandboxManager(
        local_runtime=podman_runtime,
        cloud_runtime=fargate_runtime,
        burst_engine=burst_engine,
        scanner=SensitivityScanner(),
        audit_logger=audit_logger,
    )

    return await manager.run(workspace=workspace, task=args.task, config=config)


def _cmd_run(args: argparse.Namespace) -> None:
    """Handle 'sandboxshift run' subcommand."""
    _load_fargate_env()
    workspace = _validate_workspace(args.workspace)

    if args.allow:
        _validate_allow_hosts(list(args.allow))

    # Bounds check memory and cpu only when the flag was explicitly passed.
    # When the value is None the YAML fallback (applied in _run_async) takes
    # effect — bounds on YAML-sourced values are enforced by the Fargate API.
    if args.memory_mb is not None and not (_MEMORY_MB_MIN <= args.memory_mb <= _MEMORY_MB_MAX):
        print(
            f"Error: --memory-mb must be between {_MEMORY_MB_MIN} and {_MEMORY_MB_MAX}",
            file=sys.stderr,
        )
        sys.exit(1)
    if args.cpu is not None and not (_CPU_MIN <= args.cpu <= _CPU_MAX):
        print(
            f"Error: --cpu must be between {_CPU_MIN} and {_CPU_MAX}",
            file=sys.stderr,
        )
        sys.exit(1)

    try:
        result = asyncio.run(_run_async(args, workspace))
    except SensitivityBlockedError as e:
        print(f"Blocked: {e}", file=sys.stderr)
        sys.exit(2)
    except CloudRuntimeRequiredError as e:
        print(f"Cloud runtime required but not configured: {e}", file=sys.stderr)
        sys.exit(3)
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)

    print(f"Runtime: {result.runtime_mode}")
    print(f"Duration: {result.duration_seconds:.2f}s")
    print(f"Exit code: {result.task_result.exit_code}")
    if result.task_result.stdout:
        print(result.task_result.stdout)
    if result.task_result.stderr:
        print(result.task_result.stderr, file=sys.stderr)

    sys.exit(result.task_result.exit_code)


def _cmd_list(args: argparse.Namespace) -> None:  # noqa: ARG001
    """Handle 'sandboxshift list' subcommand.

    Reads ~/.sandboxshift/servers.json and prints a table of running cloud
    server tasks. Each row shows: instance ID, public URL(s), and region.

    servers.json is written by FargateRuntime._save_server_info() every time
    a server task starts, and cleaned up by 'sandboxshift stop'. If the user
    closed their terminal without stopping, entries remain here and can be
    stopped with 'sandboxshift stop <instance_id>'.
    """
    if not _SERVERS_FILE.exists():
        print("No running cloud servers found.")
        return

    try:
        servers: dict = json.loads(_SERVERS_FILE.read_text(encoding="utf-8"))
    except Exception as e:  # noqa: BLE001
        print(f"Error reading servers file: {e}", file=sys.stderr)
        sys.exit(1)

    if not servers:
        print("No running cloud servers found.")
        return

    # Column widths
    id_w = 24
    url_w = 45

    print(f"{'INSTANCE ID':<{id_w}}  {'URL(S)':<{url_w}}  REGION")
    print("-" * (id_w + url_w + 12))
    for sid, info in servers.items():
        public_ip = info.get("public_ip")
        ports = info.get("ports", [])
        region = info.get("region", "unknown")
        if public_ip and ports:
            urls = "  ".join(f"http://{public_ip}:{c}" for _, c in ports)
        elif public_ip:
            urls = public_ip
        else:
            urls = "(IP pending — check ECS console)"
        print(f"{sid:<{id_w}}  {urls:<{url_w}}  {region}")

    print()
    print(f"Use 'sandboxshift stop <instance_id>' to stop a running server.")


def _cmd_stop(args: argparse.Namespace) -> None:
    """Handle 'sandboxshift stop <instance_id>' subcommand.

    Stops a running cloud server task launched by FargateRuntime in server mode.
    Reads task info from ~/.sandboxshift/servers.json, calls ECS stop_task,
    and removes the entry from the file.
    """
    _load_fargate_env()

    import boto3  # local import — only needed for this subcommand

    if not _SERVERS_FILE.exists():
        print("No running cloud servers found.", file=sys.stderr)
        sys.exit(1)

    try:
        servers: dict = json.loads(_SERVERS_FILE.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"Error reading servers file: {e}", file=sys.stderr)
        sys.exit(1)

    instance_id = args.instance_id

    if instance_id not in servers:
        print(f"No server found with instance ID: {instance_id}", file=sys.stderr)
        if servers:
            print("Running servers:")
            for sid, info in servers.items():
                ip = info.get("public_ip", "unknown")
                ports = info.get("ports", [])
                urls = ", ".join(f"http://{ip}:{c}" for _, c in ports) if ip else sid
                print(f"  {sid}  {urls}")
        sys.exit(1)

    info = servers[instance_id]
    region = info.get("region") or os.environ.get("FARGATE_REGION", "")
    cluster_arn = info.get("cluster_arn", "")
    ecs_task_arn = info.get("ecs_task_arn", "")

    if not region or not cluster_arn or not ecs_task_arn:
        print(
            f"Error: incomplete server info for {instance_id} — "
            "cannot stop task. Stop it manually via the AWS console.",
            file=sys.stderr,
        )
        sys.exit(1)

    try:
        session = boto3.Session()
        ecs = session.client("ecs", region_name=region)
        ecs.stop_task(
            cluster=cluster_arn,
            task=ecs_task_arn,
            reason="sandboxshift stop command",
        )
        print(f"Stopped server {instance_id}")

        # Remove from servers.json
        del servers[instance_id]
        _SERVERS_FILE.write_text(json.dumps(servers, indent=2), encoding="utf-8")

    except Exception as e:
        print(f"Error stopping task: {e}", file=sys.stderr)
        sys.exit(1)


def _cmd_audit_tail(args: argparse.Namespace) -> None:
    """Handle 'sandboxshift audit tail' subcommand."""
    _load_fargate_env()
    audit_log_path = _resolve_audit_log(args)

    if not audit_log_path.exists():
        print(f"No audit log found at {audit_log_path}")
        return

    try:
        lines = audit_log_path.read_text(encoding="utf-8").splitlines()
    except OSError as e:
        print(f"Error reading audit log: {e}", file=sys.stderr)
        sys.exit(1)

    n = getattr(args, "lines", 20)
    tail = lines[-n:] if len(lines) > n else lines

    for line in tail:
        try:
            entry = json.loads(line)
            print(json.dumps(entry, indent=2))
        except json.JSONDecodeError:
            print(line)


